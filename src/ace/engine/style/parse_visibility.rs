pub(crate) fn parse_visibility(val: &str) -> CssVisibility {
    match val.trim() {
        "visible" => CssVisibility::Visible,
        "hidden" => CssVisibility::Hidden,
        "collapse" => CssVisibility::Collapse,
        _ => CssVisibility::Visible,
    }
}
