// Media Query Helpers
pub fn matches_media_query(query: &str, vw: f32, vh: f32, color_scheme: &str) -> bool {
    let query = query.trim();
    if query.is_empty() {
        return true;
    }

    // OR logic (comma separated)
    for part in query.split(',') {
        if matches_media_query_part(part, vw, vh, color_scheme) {
            return true;
        }
    }
    false
}
