pub(crate) fn parse_border_radius(val: &str) -> f32 {
    let value = value.trim();
    if let Some(n) = val.strip_suffix("px") {
        if let Ok(num) = n.trim().parse::<f32>() {
            return num;
        }
    }
    if let Some(n) = val.strip_suffix("%") {
        if let Ok(num) = n.trim().parse::<f32>() {
            return num;
        }
    }
    0.0
}
