pub(crate) fn parse_text_align(val: &str) -> CssTextAlign {
    match val.trim() {
        "left" => CssTextAlign::Left,
        "right" => CssTextAlign::Right,
        "center" => CssTextAlign::Center,
        "justify" => CssTextAlign::Justify,
        "start" => CssTextAlign::Start,
        "end" => CssTextAlign::End,
        _ => CssTextAlign::Left,
    }
}
