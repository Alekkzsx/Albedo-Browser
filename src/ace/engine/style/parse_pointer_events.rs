pub(crate) fn parse_pointer_events(val: &str) -> CssPointerEvents {
    match val.trim() {
        "auto" => CssPointerEvents::Auto,
        "none" => CssPointerEvents::None,
        _ => CssPointerEvents::Auto,
    }
}
